window.getPresetById = function getPresetById(id) {
  return window.PRESET_CATALOG.find(p => p.id === id) || null;
};

window.buildPresetState = function buildPresetState(presetId, varIdx = 0, currentCrop = null, mixOverride = null) {
  const base = window.freshState();
  if (currentCrop) base.crop = window.deepClone(currentCrop);
  const p = window.getPresetById(presetId);
  if (!p) return base;
  let st = window.mergeState(base, p.base);
  const v = p.variations && p.variations[varIdx];
  if (v && v.patch) st = window.mergeState(st, v.patch);
  st.preset = {
    id: presetId,
    variation: varIdx,
    mix: mixOverride !== null ? mixOverride : window.DEFAULT_PRESET_MIX,
  };
  return st;
};

