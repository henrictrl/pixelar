// desenho em texto → caminho SVG (um retângulo por trecho contínuo de cada linha)
const ICON_PATHS = {};
function pixelPath(rows) {
    let d = '';
    rows.forEach((r, y) => {
        let x = 0;
        while (x < r.length) {
            if (r[x] !== '#') { x++; continue; }
            let e = x; while (e < r.length && r[e] === '#') e++;
            d += `M${x} ${y}h${e - x}v1H${x}z`;
            x = e;
        }
    });
    return d;
}
// os desenhos têm alturas diferentes: centraliza na vertical (sem meio pixel)
Object.keys(PIXEL_ART).forEach(k => {
    const rows = PIXEL_ART[k].slice();
    while (rows.length && !rows[rows.length - 1].includes('#')) rows.pop();
    let top = 0; while (top < rows.length && !rows[top].includes('#')) top++;
    const body = rows.slice(top), off = Math.floor((12 - body.length) / 2);
    ICON_PATHS[k] = pixelPath([...Array(off).fill(''), ...body]);
});
function icon(name, cls = '') {
    return `<svg class="ic px ${cls}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true"><path d="${ICON_PATHS[name] || ICON_PATHS.sparkle}"/></svg>`;
}
